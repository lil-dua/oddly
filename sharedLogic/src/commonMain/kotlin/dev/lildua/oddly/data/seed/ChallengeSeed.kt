/**
 * Bundled challenge content (spec §10). Ships inside the app so the daily loop
 * works with zero network.
 *
 * Every string is bilingual: an English reader gets English challenges, not an
 * English shell around Vietnamese content.
 *
 * 216 in total: twelve per category and difficulty, 36 per category. Easy is
 * doable right now, with no preparation, in a few minutes. Medium takes a
 * little planning or focus, ends in a small finished result, or is a rule held
 * for part of the day. A Hard challenge is hard for a reason, not just longer:
 * real effort (a finished product in 30-120 minutes), a new skill done once,
 * something that takes nerve to say or do, or a rule held all day. Never risky
 * or costly.
 *
 * Sized against [ChallengeSelector]'s 30-day cooldown rather than against a
 * round number: a user whose interests narrow the pool to a single category
 * needs at least 31 challenges there so nothing repeats inside a month.
 * Add to the END of each list as content is written, no code changes required
 * — completions store only the challenge id, so a longer library needs no
 * migration. Never rename a published id (see PublishedContent).
 */
object ChallengeSeed {

    val all: List<Challenge> = buildList {
        addAll(health)
        addAll(relationships)
        addAll(selfGrowth)
        addAll(creativity)
        addAll(finance)
        addAll(lifeExperience)
    }

    /** Declared after [all] so it is built from the finished list (object init order). */
    private val byIdIndex: Map<String, Challenge> = all.associateBy { it.id }

    /** O(1): stats, selector and AppState look challenges up once per completion. */
    fun byId(id: String): Challenge? = byIdIndex[id]

    fun byCategory(category: Category): List<Challenge> = all.filter { it.category == category }
}

/** Shorthand so a seed entry stays readable at two languages per field. */
private fun t(vi: String, en: String) = LocalizedText(vi = vi, en = en)

private fun challenge(
    id: String,
    title: LocalizedText,
    shortDescription: LocalizedText,
    category: Category,
    difficulty: Difficulty,
    minutes: Int,
    why: LocalizedText,
    how: List<LocalizedText>,
) = Challenge(
    id = id,
    title = title,
    shortDescription = shortDescription,
    category = category,
    difficulty = difficulty,
    estimatedMinutes = minutes,
    whyItMatters = why,
    howToDoIt = how,
)

