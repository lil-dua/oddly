/**
 * Bundled challenge content (spec §10). Ships inside the app so the daily loop
 * works with zero network.
 *
 * Every string is bilingual: an English reader gets English challenges, not an
 * English shell around Vietnamese content. Twenty per category, 120 in total.
 *
 * Sized against [ChallengeSelector]'s 30-day cooldown rather than against a
 * round number: a user whose interests narrow the pool to two categories still
 * has forty challenges to draw from, so nothing repeats inside a month. The
 * spec targets ~240 for beta; add to [all] as content is written, no code
 * changes required — completions store only the challenge id, so a longer
 * library needs no migration.
 */
object ChallengeSeed {

    val all: List<Challenge> = buildList {
        addAll(health)
        addAll(relationships)
        addAll(selfGrowth)
        addAll(creativity)
        addAll(finance)
        addAll(lifeExperience)
    }

    fun byId(id: String): Challenge? = all.firstOrNull { it.id == id }

    fun byCategory(category: Category): List<Challenge> = all.filter { it.category == category }
}

/** Shorthand so a seed entry stays readable at two languages per field. */
private fun t(vi: String, en: String) = LocalizedText(vi = vi, en = en)

private fun challenge(
    id: String,
    title: LocalizedText,
    shortDescription: LocalizedText,
    category: Category,
    difficulty: Difficulty,
    minutes: Int,
    why: LocalizedText,
    how: List<LocalizedText>,
) = Challenge(
    id = id,
    title = title,
    shortDescription = shortDescription,
    category = category,
    difficulty = difficulty,
    estimatedMinutes = minutes,
    whyItMatters = why,
    howToDoIt = how,
)

